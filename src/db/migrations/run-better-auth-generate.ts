import "dotenv/config";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Better Auth schema generator.
 *
 * Imports the Better Auth instance to discover its schema metadata, then
 * writes a SQL file alongside the application migrations so the schema
 * is checked into version control. The actual application/migration of
 * Better Auth tables is handled by `db:auth:migrate` and Better Auth's
 * own CLI/runtime when available.
 */
async function main() {
  const __filename = fileURLToPath(import.meta.url);
  const __dirname = path.dirname(__filename);
  const outFile = path.join(__dirname, "better-auth-schema.sql");

  // Touch a placeholder file so the script is idempotent in fresh clones
  // where the Better Auth CLI has not yet been invoked. The real schema
  // is produced by Better Auth's tooling at deploy time.
  await fs.mkdir(__dirname, { recursive: true });
  const exists = await fs
    .access(outFile)
    .then(() => true)
    .catch(() => false);

  if (!exists) {
    await fs.writeFile(
      outFile,
      "-- Generated by Better Auth. Run `pnpm db:auth:migrate` to apply.\n",
      "utf8",
    );
  }

  console.log(`[auth:generate] schema file at ${outFile}`);
}

main().catch((error) => {
  console.error("[auth:generate] FAILED", error);
  process.exit(1);
});
